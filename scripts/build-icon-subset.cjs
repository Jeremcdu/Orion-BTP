/* Build a local runtime subset from the unmodified Lucide 0.468.0 distribution.
 * Definitions retain their upstream ISC/MIT licence in assets/LUCIDE-LICENSE.txt. */
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..');
const lucide = require(path.join(root, 'assets/lucide-0.468.0.min.js'));
const pages = ['index.html', 'm42/index.html', 'm43/index.html', 'm78/index.html'];
const tokens = new Set(pages.flatMap(file => fs.readFileSync(path.join(root, file), 'utf8').match(/[a-z][a-z0-9]*(?:-[a-z0-9]+)*/g) || []));
const icons = {};
for (const name of [...tokens].sort()) {
  const key = name.split('-').map(s => s[0].toUpperCase() + s.slice(1)).join('');
  if (lucide.icons[key]) icons[name] = lucide.icons[key];
}
const runtime = `/* Lucide 0.468.0 subset. See LUCIDE-LICENSE.txt. Generated by scripts/build-icon-subset.cjs. */
(() => {
'use strict';
const icons = ${JSON.stringify(icons)};
function createIcons() {
  for (const node of document.querySelectorAll('[data-lucide]')) {
    const name = node.getAttribute('data-lucide'), definition = icons[name];
    if (node.querySelector('use[href*="orion-brand.svg"]')) continue;
    if (node.localName === 'svg' && node.getAttribute('data-orion-rendered') === name) continue;
    if (!definition) { console.warn('Unknown Orion icon:', name); continue; }
    const render = ([tag, attributes, children = []]) => {
      const element = document.createElementNS('http://www.w3.org/2000/svg', tag);
      for (const [key, value] of Object.entries(attributes)) element.setAttribute(key, value);
      for (const child of children) element.appendChild(render(child));
      return element;
    };
    const svg = render(definition);
    for (const attribute of node.attributes) svg.setAttribute(attribute.name, attribute.value);
    const retainedClass = (node.getAttribute('class') || '').split(/\\s+/).filter(c => c !== 'lucide' && !c.startsWith('lucide-')).join(' ');
    svg.setAttribute('class', ('lucide lucide-' + name + ' ' + retainedClass).trim());
    svg.setAttribute('data-orion-rendered', name);
    if (!svg.hasAttribute('aria-label')) svg.setAttribute('aria-hidden', 'true');
    node.replaceWith(svg);
  }
}
window.lucide = { createIcons };
})();
`;
fs.writeFileSync(path.join(root, 'assets/orion-icons.js'), runtime);
console.log(Object.keys(icons).length + ' icons, ' + Buffer.byteLength(runtime) + ' bytes (full distribution: ' + fs.statSync(path.join(root, 'assets/lucide-0.468.0.min.js')).size + ')');
